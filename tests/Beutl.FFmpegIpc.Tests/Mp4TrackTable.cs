using System.Buffers.Binary;
using System.Text;

namespace Beutl.FFmpegIpc.Tests;

internal static class Mp4TrackTable
{
    public static string[] ReadTypes(string path)
    {
        var movie = FindBox(File.ReadAllBytes(path), "moov");
        return ReadBoxes(movie)
            .Where(box => box.Type == "trak")
            .Select(box =>
            {
                var media = FindBox(box.Payload, "mdia");
                var handler = FindBox(media, "hdlr");
                return Encoding.ASCII.GetString(handler.Span.Slice(8, 4));
            })
            .ToArray();
    }

    private static ReadOnlyMemory<byte> FindBox(ReadOnlyMemory<byte> data, string type)
        => ReadBoxes(data).Single(box => box.Type == type).Payload;

    // The short MP4 files generated by the tests use 32-bit box sizes.
    private static IEnumerable<(string Type, ReadOnlyMemory<byte> Payload)> ReadBoxes(ReadOnlyMemory<byte> data)
    {
        while (!data.IsEmpty)
        {
            Assert.That(data.Length, Is.GreaterThanOrEqualTo(8));
            int size = BinaryPrimitives.ReadInt32BigEndian(data.Span);
            Assert.That(size, Is.InRange(8, data.Length));
            string type = Encoding.ASCII.GetString(data.Span.Slice(4, 4));
            yield return (type, data.Slice(8, size - 8));
            data = data[size..];
        }
    }
}
